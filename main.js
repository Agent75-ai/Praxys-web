function renderSection(id, sec, opts={}){
  const cls='praxys-section '+(opts.alt?'alt ':'')+(opts.dark?'dark ':'');
  const cards=sec.cards||[];
  const grid=cards.map(c=>Array.isArray(c)&&c.length===5?cardSolution(c):cardSimple(esc(c[0]),esc(c[1]))).join('');
  return `<section id="${id}" class="${cls}"><div class="wrap"><div class="serv-head reveal"><span class="eyebrow">${esc(sec.eyebrow)}</span><h2>${esc(sec.title)}</h2><p class="praxys-lead">${esc(sec.lead||'')}</p></div><div class="praxys-grid">${grid}</div>${opts.cta?ctaBand():''}</div></section>`;
}
